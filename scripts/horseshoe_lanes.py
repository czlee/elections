#!/usr/bin/env python3
"""Seats per arch lane for the horseshoe chamber chart (Parliament.svelte).

The chart is two straight legs joined by an arch, LANES seats wide, with seats a pitch P apart. For a
House of n seats, the legs take whole rows (2 * LANES seats each: one per lane per leg) and the arch
takes the rest. This works out how many seats go in each arch lane, and writes the answer into
Parliament.svelte as a small table, so the component doesn't have to search for it.

The rules:

- Every lane has an even number of seats, except that an odd n has exactly one odd lane. That way the
  majority line (the vertical line through the middle) falls between seats, or, for an odd n, through
  the one median seat.
- Leg rows = round((n - D) / (2 * LANES)), where D is the arch size with each lane rounded to an even
  number of seats at pitch P. So House sizes in the same block of 2 * LANES share leg rows (and so
  height); the block starts at n = D - LANES + 2 * LANES * rows, which is where the arch is smallest.
- At the start of a block the arch is the best even split: the lane counts, within 8 of each lane's
  default, that keep the seat spacing along each lane (pi * radius / seats) closest to P, measured as
  the sum of squared deviations.
- Each further seat in the block goes in one lane only, so House sizes in the same block differ only
  by added seats, wherever you start from (this is the stability that makes comparing two House
  sizes look sensible). An odd lane has to grow to even again; otherwise the seat goes in the lane
  where it worsens the spacing least.

So the arch is a table indexed by how many seats past the start of the block, 0 to 2 * LANES - 1,
and the same for every block. With LANES = 4, P = 17, R0 = 2.6 * P, that is n mod 8.

LANES, P and R0 are read from the first file given, which must agree with the rest.

    python3 scripts/horseshoe_lanes.py sites/*/src/lib/components/Parliament.svelte
        checks the table in each file (exit status 1 if one is out of date or missing)
    python3 scripts/horseshoe_lanes.py --write sites/*/src/lib/components/Parliament.svelte
        rewrites the table in each (between the BEGIN and END generated lines)
"""

import argparse
import itertools
import math
import re
import sys

BEGIN = "// BEGIN generated by scripts/horseshoe_lanes.py: don't edit, rerun it if LANES, P or R0 change"
END = "// END generated"


def read_constants(text):
    """LANES, P and R0 as written in the component."""
    lanes = int(re.search(r"const LANES = (\d+);", text).group(1))
    pitch = int(re.search(r"const P = (\d+);", text).group(1))
    r0 = float(re.search(r"const R0 = ([\d.]+) \* P;", text).group(1)) * pitch
    return lanes, pitch, r0


def arch_table(lanes, pitch, r0):
    """Lane seat counts (inner lane first) for each offset 0 to 2 * lanes - 1 from the start of a block."""
    radii = [r0 + i * pitch for i in range(lanes)]

    def cost(i, k):
        return (math.pi * radii[i] / k - pitch) ** 2

    # math.floor(x + 0.5) is JavaScript's Math.round; Python's round() rounds halves to even.
    default = [2 * math.floor(math.pi * r / (2 * pitch) + 0.5) for r in radii]
    start = sum(default) - lanes

    best, best_cost = None, math.inf
    for ks in itertools.product(*(range(max(2, d - 8), d + 9) for d in default)):
        if sum(ks) != start or sum(k % 2 for k in ks) > 1:
            continue
        c = sum(cost(i, k) for i, k in enumerate(ks))
        if c < best_cost:
            best, best_cost = list(ks), c

    table = [list(best)]
    for _ in range(2 * lanes - 1):
        ks = list(table[-1])
        odd = [i for i, k in enumerate(ks) if k % 2]
        if odd:
            pick = odd[0]
        else:
            pick = min(range(lanes), key=lambda i: cost(i, ks[i] + 1) - cost(i, ks[i]))
        ks[pick] += 1
        table.append(ks)
    return table


def block(table):
    rows = ",\n".join(f"\t\t[{', '.join(map(str, ks))}]" for ks in table)
    return f"\t{BEGIN}\n\tconst ARCH_LANES = [\n{rows}\n\t];\n\t{END}"


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("files", nargs="+", help="Parliament.svelte files")
    ap.add_argument("--write", action="store_true", help="rewrite the table instead of checking it")
    args = ap.parse_args()

    texts = {f: open(f).read() for f in args.files}
    constants = {f: read_constants(t) for f, t in texts.items()}
    first = constants[args.files[0]]
    for f, c in constants.items():
        if c != first:
            sys.exit(f"{f}: LANES, P, R0 = {c}, but {args.files[0]} has {first}")
    table = arch_table(*first)
    new = block(table)
    pattern = re.compile(r"\t// BEGIN generated by scripts/horseshoe_lanes\.py.*?\t// END generated", re.S)

    stale = False
    for f, text in texts.items():
        match = pattern.search(text)
        if match is None:
            print(f"{f}: no generated table")
            stale = True
        elif match.group(0) == new:
            print(f"{f}: up to date")
        elif args.write:
            open(f, "w").write(text[: match.start()] + new + text[match.end():])
            print(f"{f}: rewritten")
        else:
            print(f"{f}: out of date (rerun with --write)")
            stale = True
    print(f"\nLANES {first[0]}, P {first[1]}, R0 {first[2]:g}; arch lanes by seats past the block start:")
    for i, ks in enumerate(table):
        print(f"  +{i}: {ks} = {sum(ks)} seats")
    sys.exit(1 if stale else 0)


if __name__ == "__main__":
    main()
